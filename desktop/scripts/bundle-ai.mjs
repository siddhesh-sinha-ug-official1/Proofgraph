/**
 * bundle-ai.mjs — bundle the AI server into a single CJS file.
 *
 * The output (resources/ai-server.cjs) runs on Electron's bundled
 * Node.js via ELECTRON_RUN_AS_NODE=1, so it must be self-contained:
 * all local imports inlined, only node:* builtins external.
 *
 * Usage:  node scripts/bundle-ai.mjs
 */
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..', '..');

await build({
  entryPoints: [path.join(repoRoot, 'ai/server/cli.ts')],
  outfile: path.join(__dirname, '..', 'resources', 'ai-server.cjs'),
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
  sourcemap: false,
  // Everything under node:* is external (built into Electron's Node);
  // all local imports from packages/ and ai/ are inlined.
  external: ['node:*'],
  // The AI server's CLI entry uses process.argv, same as standalone.
  banner: {
    js: '// ProofGraph AI server — bundled for Electron production mode.\n'
      + '// This file is auto-generated by desktop/scripts/bundle-ai.mjs.\n',
  },
});

console.log('[bundle-ai] resources/ai-server.cjs written');
